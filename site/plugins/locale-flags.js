/**
 * Generates the locale picker's flag rules from `src/locales.js`.
 *
 * The flags used to be three hand-written CSS blocks, one per locale, each naming an `htmlLang` prefix
 * and an SVG filename. That is a per-locale edit in a 4,600-line stylesheet, in a file nothing would
 * flag as incomplete: a missing block is a missing flag, which looks like a design choice rather than
 * an omission. Generating them means adding a locale is `src/locales.js` plus the asset.
 *
 * Only the per-locale rules are here. The locale-agnostic scaffolding, the flag box and the navbar
 * control, stays in `src/css/custom.css` where it can be read alongside the rest of the navbar.
 *
 * Injected as a style tag rather than written to a file. A generated file inside `src/` is a build
 * artifact that looks like source, gets edited by someone reasonably assuming it is source, and then
 * loses that edit on the next build. `injectHtmlTags` has no such failure mode.
 *
 * Selectors are matched on the language subtag prefix, not the full tag, so correcting a region code in
 * `src/locales.js` cannot silently drop the flags. `zh-Hans` is emitted in full because a later
 * `zh-Hant-TW` must not inherit the Simplified flag: the prefix is derived by dropping only the region,
 * which keeps the script subtag that distinguishes them.
 */
import {LOCALES, FLAG_DIR} from '../src/locales.js';

/**
 * The prefix a flag rule matches: the tag without its trailing region subtag.
 *
 * `ru-RU` becomes `ru`, `zh-Hans-CN` becomes `zh-Hans`, `en` stays `en`. Dropping the region is what
 * makes the rule survive a region correction; keeping the script is what keeps two Chineses apart.
 */
function langPrefix(htmlLang) {
  const parts = htmlLang.split('-');
  if (parts.length < 2) return htmlLang;
  const last = parts[parts.length - 1];
  const isRegion = /^([A-Z]{2}|\d{3})$/.test(last);
  return isRegion ? parts.slice(0, -1).join('-') : htmlLang;
}

export function flagCss(locales = LOCALES, dir = FLAG_DIR) {
  const rules = locales.map((l) => {
    const p = langPrefix(l.htmlLang);
    const url = `url('${dir}/${l.flag}')`;
    return [
      `.dropdown__link[lang^='${p}']::before,`,
      `.menu__link[lang^='${p}']::before,`,
      `html[lang^='${p}'] .navbar__link.epicLocalePicker::before {`,
      `  background-image: ${url};`,
      `}`,
    ].join('\n');
  });
  return `/* generated by plugins/locale-flags.js from src/locales.js, do not edit */\n${rules.join('\n\n')}\n`;
}

export default function localeFlags() {
  return {
    name: 'epic-locale-flags',
    injectHtmlTags() {
      return {
        headTags: [
          {
            tagName: 'style',
            attributes: {type: 'text/css', 'data-epic-locale-flags': 'true'},
            innerHTML: flagCss(),
          },
        ],
      };
    },
  };
}
