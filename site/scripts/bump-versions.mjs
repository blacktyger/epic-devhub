#!/usr/bin/env node
/**
 * Release bump for the docs site.
 *
 *   npm run versions:bump    fetch upstream releases, verify the binaries, write src/data/releases.js
 *   npm run versions:check   compare upstream with the committed releases.js, exit 1 if out of date
 *
 * Reads the GitHub releases API for each component, picks the newest semver release that is neither a
 * draft nor a prerelease, and for each platform takes the asset from the newest release in the same
 * major line that ships one. Every chosen asset is downloaded, its SHA-256 is computed and compared
 * with the published checksum file, and the archive is listed to record where the binary lives.
 *
 * Zero dependencies: Node 20+ global fetch, node:crypto, and the system `tar` and `unzip`.
 * Set GITHUB_TOKEN to authenticate API calls (60 requests an hour unauthenticated is enough for a
 * few runs; each run makes one API request per component per 100 releases).
 */

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { createWriteStream } from 'node:fs';
import { mkdtemp, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { Readable, Transform } from 'node:stream';
import { pipeline } from 'node:stream/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
// An ES module rather than JSON, so it imports the same way in webpack and in plain Node, where a JSON
// import would need import attributes.
export const OUTPUT = path.resolve(SCRIPT_DIR, '../src/data/releases.js');

const COMMENT =
  'Generated by site/scripts/bump-versions.mjs from the GitHub releases API. Do not edit by hand; run npm run versions:bump.';

// Key order here is the key order in releases.js.
export const COMPONENTS = {
  node: { repo: 'EpicCash/epic', binary: 'epic' },
  wallet: { repo: 'EpicCash/epic-wallet', binary: 'epic-wallet' },
  miner: { repo: 'EpicCash/epic-miner', binary: 'epic-miner' },
};

export const PLATFORMS = ['linux', 'windows', 'mac'];

const PLATFORM_RULES = {
  linux: /linux-amd64.*\.tar\.gz$/,
  windows: /^Windows[-_].*\.zip$/,
  mac: /^MacOS-.*\.zip$/,
};

const API_TIMEOUT_MS = 30_000;
const DOWNLOAD_TIMEOUT_MS = 10 * 60_000;
const ATTEMPTS = 3;

// ---------------------------------------------------------------------------------------------
// Pure helpers (exported for tests)

/** Parse a release tag as semver. Returns null for anything that is not `[v]MAJOR.MINOR.PATCH[-pre][+build]`. */
export function parseSemver(tag) {
  if (typeof tag !== 'string') return null;
  const m = /^v?(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-([0-9A-Za-z.-]+))?(?:\+[0-9A-Za-z.-]+)?$/.exec(tag);
  if (!m) return null;
  return {
    version: tag.replace(/^v/, ''),
    major: Number(m[1]),
    minor: Number(m[2]),
    patch: Number(m[3]),
    pre: m[4] ? m[4].split('.') : [],
  };
}

/** Semver precedence: negative if a < b, positive if a > b, 0 if equal. */
export function compareSemver(a, b) {
  for (const k of ['major', 'minor', 'patch']) {
    if (a[k] !== b[k]) return a[k] - b[k];
  }
  // A version without prerelease identifiers ranks above one with them.
  if (!a.pre.length || !b.pre.length) return b.pre.length - a.pre.length;
  for (let i = 0; i < Math.max(a.pre.length, b.pre.length); i++) {
    if (a.pre[i] === undefined) return -1;
    if (b.pre[i] === undefined) return 1;
    const an = /^\d+$/.test(a.pre[i]);
    const bn = /^\d+$/.test(b.pre[i]);
    if (an && bn) {
      const d = Number(a.pre[i]) - Number(b.pre[i]);
      if (d) return d;
    } else if (an !== bn) {
      return an ? -1 : 1;
    } else if (a.pre[i] !== b.pre[i]) {
      return a.pre[i] < b.pre[i] ? -1 : 1;
    }
  }
  return 0;
}

/** Published, semver-tagged releases, newest version first. */
export function eligibleReleases(releases) {
  return releases
    .filter((r) => !r.draft && !r.prerelease)
    .map((r) => ({ release: r, semver: parseSemver(r.tag_name) }))
    .filter((x) => x.semver)
    .sort((x, y) => compareSemver(y.semver, x.semver));
}

/** Which platform an asset name belongs to, or null. Checksum files never match. */
export function platformOf(name) {
  if (/-sha256sum\.txt$/.test(name)) return null;
  for (const p of PLATFORMS) if (PLATFORM_RULES[p].test(name)) return p;
  return null;
}

export const isAppleSilicon = (name) => /aarch64|arm64/i.test(name);

export function platformLabel(platform, file) {
  if (platform === 'linux') return 'Linux x86-64';
  if (platform === 'windows') return 'Windows x86-64';
  return isAppleSilicon(file) ? 'macOS Apple silicon' : 'macOS Intel';
}

/** The asset for a platform within one release, or null. Deterministic when several match. */
export function pickAsset(assets, platform) {
  const matches = assets.filter((a) => platformOf(a.name) === platform);
  matches.sort((a, b) => {
    if (platform === 'mac' && isAppleSilicon(a.name) !== isAppleSilicon(b.name)) {
      return isAppleSilicon(a.name) ? -1 : 1;
    }
    return a.name.length - b.name.length || (a.name < b.name ? -1 : a.name > b.name ? 1 : 0);
  });
  return matches[0] ?? null;
}

export const sumFileName = (file) => file.replace(/(\.tar\.gz|\.zip)$/, '-sha256sum.txt');

/**
 * Choose the latest release and, per platform, the asset from the newest release that has one.
 * Fallback is limited to the latest release's major line: an older major (3.x against a 4.x node)
 * is a different network, and a binary from it is not a download for the current release.
 */
export function selectComponent(releases) {
  const eligible = eligibleReleases(releases);
  if (!eligible.length) return { latest: null, picks: {} };
  const latest = eligible[0];
  const line = eligible.filter((x) => x.semver.major === latest.semver.major);
  const picks = {};
  for (const platform of PLATFORMS) {
    for (const { release, semver } of line) {
      const asset = pickAsset(release.assets ?? [], platform);
      if (!asset) continue;
      const sumName = sumFileName(asset.name);
      picks[platform] = {
        release,
        version: semver.version,
        asset,
        sumAsset: (release.assets ?? []).find((a) => a.name === sumName) ?? null,
        sumName,
      };
      break;
    }
  }
  return { latest, picks };
}

/** Extract the hash for `file` from a sha256sum-style text. */
export function parseChecksum(text, file) {
  const entries = [];
  for (const line of text.split(/\r?\n/)) {
    // `HASH  name`, `HASH *name` (sha256sum) or `SHA256 (name) = HASH` (BSD shasum --tag).
    const m = /(?:^|[^0-9a-fA-F])([0-9a-fA-F]{64})(?![0-9a-fA-F])/.exec(line);
    if (!m) continue;
    const rest = line.replace(m[1], ' ').replace(/^\s*SHA256\s*/i, '');
    const name = rest.replace(/[()=*:]/g, ' ').trim();
    entries.push({ hash: m[1].toLowerCase(), name: name ? path.posix.basename(name.replace(/\\/g, '/')) : '' });
  }
  const named = entries.find((e) => e.name === file);
  if (named) return named.hash;
  const hashes = [...new Set(entries.map((e) => e.hash))];
  if (hashes.length === 1) return hashes[0];
  throw new Error(`cannot find a SHA-256 for ${file} in its checksum file`);
}

/**
 * From an archive listing, the single top-level directory (or null when files sit at the root)
 * and the path of the binary relative to the archive root (or null if absent).
 */
export function analyseListing(entries, binaryName) {
  const clean = entries
    .map((e) => e.replace(/\\/g, '/').replace(/^(\.\/)+/, ''))
    .filter((e) => e && e !== '.' && e !== './' && !e.startsWith('__MACOSX/'));
  const tops = new Set(clean.map((e) => e.split('/')[0]));
  let unpacksTo = null;
  if (tops.size === 1) {
    const [top] = tops;
    if (clean.some((e) => e.startsWith(`${top}/`))) unpacksTo = top;
  }
  const binaries = clean
    .map((e) => e.replace(/\/$/, ''))
    .filter((e) => path.posix.basename(e) === binaryName || path.posix.basename(e) === `${binaryName}.exe`)
    .sort((a, b) => a.split('/').length - b.split('/').length || a.length - b.length);
  return { unpacksTo, binary: binaries[0] ?? null };
}

const isoDate = (s) => (s ? new Date(s).toISOString().slice(0, 10) : null);

/** Assemble one component in the fixed key order. `details` supplies sha256/unpacksTo/binary per platform. */
export function buildComponent(repo, selection, details) {
  const { latest, picks } = selection;
  const out = {
    repo,
    version: latest ? latest.semver.version : null,
    tag: latest ? latest.release.tag_name : null,
    date: latest ? isoDate(latest.release.published_at) : null,
    url: latest ? latest.release.html_url : null,
    assets: {},
  };
  for (const platform of PLATFORMS) {
    const pick = picks[platform];
    if (!pick) continue;
    const d = details[platform] ?? {};
    out.assets[platform] = {
      platform: platformLabel(platform, pick.asset.name),
      version: pick.version,
      tag: pick.release.tag_name,
      file: pick.asset.name,
      url: pick.asset.browser_download_url,
      sumFile: pick.sumAsset ? pick.sumAsset.name : null,
      sumUrl: pick.sumAsset ? pick.sumAsset.browser_download_url : null,
      sha256: d.sha256 ?? null,
      unpacksTo: d.unpacksTo ?? null,
      binary: d.binary ?? null,
    };
  }
  return out;
}

const HEADER = `/**
 * Generated by site/scripts/bump-versions.mjs from the GitHub releases API. Do not edit by hand;
 * run npm run versions:bump in site/. Pages never import this file: they read these values
 * through src/data/versions.js, the only source of truth they use.
 */
`;

export const serialise = (data) =>
  `${HEADER}export const releaseData = ${JSON.stringify(data, null, 2)};\n`;

/** Differences between two releases documents, ignoring checkedAt (and, in check mode, archive-derived fields). */
export function diff(oldDoc, newDoc, { ignore = [] } = {}) {
  const skip = new Set(['checkedAt', ...ignore]);
  const lines = [];
  const show = (v) => JSON.stringify(v, (k, x) => (skip.has(k) ? undefined : x));
  const walk = (a, b, at) => {
    const leaf = (v) => v === null || typeof v !== 'object';
    if (leaf(a) || leaf(b)) {
      if (show(a) !== show(b)) {
        lines.push(`${at}: ${show(a)} -> ${show(b)}`);
      }
      return;
    }
    const keys = [...new Set([...Object.keys(a), ...Object.keys(b)])];
    for (const k of keys) {
      if (skip.has(k)) continue;
      const next = at ? `${at}.${k}` : k;
      if (!(k in a)) lines.push(`${next}: added ${show(b[k])}`);
      else if (!(k in b)) lines.push(`${next}: removed`);
      else walk(a[k], b[k], next);
    }
  };
  walk(oldDoc ?? {}, newDoc, '');
  return lines;
}

// ---------------------------------------------------------------------------------------------
// I/O

const warnings = [];
const warn = (msg) => {
  warnings.push(msg);
  console.warn(`warning: ${msg}`);
};

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

/** GET with timeout and retry on network errors and 5xx. Throws on any other non-2xx. */
async function get(url, { headers = {}, timeout = API_TIMEOUT_MS } = {}) {
  let lastError;
  for (let attempt = 1; attempt <= ATTEMPTS; attempt++) {
    let res;
    try {
      res = await fetch(url, {
        headers: { 'User-Agent': 'epic-devhub-bump-versions', ...headers },
        redirect: 'follow',
        signal: AbortSignal.timeout(timeout),
      });
    } catch (err) {
      lastError = new Error(`GET ${url} failed: ${err.message}`);
      if (attempt < ATTEMPTS) await sleep(1000 * attempt);
      continue;
    }
    if (res.ok) return res;
    await res.body?.cancel();
    if ((res.status === 403 || res.status === 429) && res.headers.get('x-ratelimit-remaining') === '0') {
      const reset = Number(res.headers.get('x-ratelimit-reset')) * 1000;
      throw new Error(
        `GitHub API rate limit exhausted (resets ${new Date(reset).toISOString()}). Set GITHUB_TOKEN to authenticate.`,
      );
    }
    lastError = new Error(`GET ${url} returned HTTP ${res.status}`);
    if (res.status < 500) break;
    if (attempt < ATTEMPTS) await sleep(1000 * attempt);
  }
  throw lastError;
}

function apiHeaders() {
  const h = { Accept: 'application/vnd.github+json', 'X-GitHub-Api-Version': '2022-11-28' };
  if (process.env.GITHUB_TOKEN) h.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  return h;
}

/** Every release of a repo, following the Link header. */
async function fetchReleases(repo) {
  const all = [];
  let url = `https://api.github.com/repos/${repo}/releases?per_page=100`;
  while (url) {
    const res = await get(url, { headers: apiHeaders() });
    const page = await res.json();
    if (!Array.isArray(page)) throw new Error(`unexpected response from ${url}`);
    all.push(...page);
    const next = /<([^>]+)>;\s*rel="next"/.exec(res.headers.get('link') ?? '');
    url = next ? next[1] : null;
  }
  return all;
}

// Release assets are public; no Authorization is sent, so a token never follows the redirect to the
// asset CDN.
async function fetchText(url) {
  return (await get(url)).text();
}

async function downloadAndHash(url, dest) {
  const res = await get(url, { timeout: DOWNLOAD_TIMEOUT_MS });
  const hash = createHash('sha256');
  const tap = new Transform({
    transform(chunk, _enc, cb) {
      hash.update(chunk);
      cb(null, chunk);
    },
  });
  await pipeline(Readable.fromWeb(res.body), tap, createWriteStream(dest));
  return hash.digest('hex');
}

function listArchive(file) {
  const opts = { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 };
  const out = file.endsWith('.zip')
    ? execFileSync('unzip', ['-Z1', file], opts)
    : execFileSync('tar', ['tzf', file], opts);
  return out.split(/\r?\n/).filter(Boolean);
}

async function readCommitted() {
  try {
    await readFile(OUTPUT, 'utf8'); // ENOENT check before importing
    const mod = await import(`${pathToFileURL(OUTPUT).href}?t=${Date.now()}`);
    return mod.releaseData;
  } catch (err) {
    if (err.code === 'ENOENT') return null;
    throw new Error(`cannot read ${OUTPUT}: ${err.message}`);
  }
}

// ---------------------------------------------------------------------------------------------
// Main

async function run({ check }) {
  const committed = await readCommitted();
  const workDir = check ? null : await mkdtemp(path.join(tmpdir(), 'epic-bump-'));
  const components = {};
  try {
    for (const [name, { repo, binary }] of Object.entries(COMPONENTS)) {
      const releases = await fetchReleases(repo);
      const selection = selectComponent(releases);
      const latest = selection.latest;
      console.log(`${name}: ${repo} ${latest ? latest.release.tag_name : 'no published release'}`);
      const details = {};
      for (const [platform, pick] of Object.entries(selection.picks)) {
        const d = {};
        details[platform] = d;
        const where = `${repo} ${pick.release.tag_name} ${pick.asset.name}`;
        let published = null;
        if (pick.sumAsset) {
          published = parseChecksum(await fetchText(pick.sumAsset.browser_download_url), pick.asset.name);
        } else {
          warn(`${where}: no ${pick.sumName} in the release; sha256 recorded as null`);
        }
        d.sha256 = published;
        if (check) continue;
        const dest = path.join(workDir, `${name}-${platform}-${path.basename(pick.asset.name)}`);
        process.stdout.write(`  ${platform}: downloading ${pick.asset.name} ... `);
        const actual = await downloadAndHash(pick.asset.browser_download_url, dest);
        if (published && actual !== published) {
          console.log('MISMATCH');
          throw new Error(`${where}: SHA-256 mismatch. Published ${published}, downloaded ${actual}.`);
        }
        console.log(published ? 'sha256 ok' : 'sha256 unverified');
        const listing = analyseListing(listArchive(dest), binary);
        d.unpacksTo = listing.unpacksTo;
        d.binary = listing.binary;
        if (!listing.binary) warn(`${where}: no ${binary} binary found in the archive; binary recorded as null`);
        await rm(dest, { force: true });
      }
      components[name] = buildComponent(repo, selection, details);
    }
  } finally {
    if (workDir) await rm(workDir, { recursive: true, force: true });
  }

  const doc = {
    $comment: COMMENT,
    checkedAt: new Date().toISOString().slice(0, 10),
    components,
  };

  console.log('');
  if (check) {
    if (!committed) {
      console.log(`${path.relative(process.cwd(), OUTPUT)} does not exist. Run npm run versions:bump.`);
      return 1;
    }
    // unpacksTo and binary need the archive, which check mode does not download. They are fixed by
    // sha256, which is compared, so leaving them out loses nothing.
    const changes = diff(committed, doc, { ignore: ['unpacksTo', 'binary'] });
    if (changes.length) {
      console.log(`releases.js is out of date (${changes.length} difference${changes.length === 1 ? '' : 's'}):`);
      for (const c of changes) console.log(`  ${c}`);
      console.log('\nRun npm run versions:bump.');
      return 1;
    }
    console.log(`releases.js is current (checked ${doc.checkedAt}).`);
    return 0;
  }

  const tmp = `${OUTPUT}.tmp`;
  await writeFile(tmp, serialise(doc));
  await rename(tmp, OUTPUT);

  console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)}`);
  console.log('');
  console.log('Summary');
  for (const [name, c] of Object.entries(components)) {
    const old = committed?.components?.[name]?.version ?? null;
    const mark = old === c.version ? '(unchanged)' : '(changed)';
    console.log(`  ${name.padEnd(7)} ${String(old)} -> ${String(c.version)} ${mark}`);
    for (const [platform, a] of Object.entries(c.assets)) {
      const from = a.version === c.version ? '' : `  (from ${a.tag})`;
      console.log(`           ${platform.padEnd(8)} ${a.file}${from}`);
    }
  }
  const changes = committed ? diff(committed, doc) : [];
  if (!committed) console.log('\nNo previous releases.js; wrote a new one.');
  else console.log(changes.length ? `\n${changes.length} field(s) changed:` : '\nNo field changed apart from checkedAt.');
  for (const c of changes) console.log(`  ${c}`);
  if (warnings.length) {
    console.log(`\n${warnings.length} warning(s):`);
    for (const w of warnings) console.log(`  ${w}`);
  }
  console.log('\nNext: npm run build, then cd ../audit && npm run versions && npm run sources');
  return 0;
}

const USAGE = `usage: node scripts/bump-versions.mjs [--check]

  (no flag)  fetch upstream releases, verify assets, write src/data/releases.js
  --check    compare upstream with the committed releases.js; exit 1 if out of date
  GITHUB_TOKEN in the environment authenticates GitHub API calls.`;

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  if (args.includes('-h') || args.includes('--help')) {
    console.log(USAGE);
    process.exit(0);
  }
  const unknown = args.filter((a) => a !== '--check');
  if (unknown.length) {
    console.error(`unknown argument: ${unknown.join(' ')}\n\n${USAGE}`);
    process.exit(2);
  }
  run({ check: args.includes('--check') }).then(
    (code) => process.exit(code),
    (err) => {
      console.error(`\nerror: ${err.message}`);
      process.exit(1);
    },
  );
}
